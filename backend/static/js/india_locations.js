/**
 * Initialize cascading state and district dropdowns, city pre-fill, and automatic pincode population.
 */
function setupLocationCascade(config) {
    const stateEl = document.getElementById(config.stateSelectId);
    const districtEl = document.getElementById(config.districtSelectId);
    const cityEl = document.getElementById(config.cityInputId);
    const pincodeEl = document.getElementById(config.pincodeInputId);

    if (!stateEl || !districtEl) return;

    // 1. Populate state dropdown
    stateEl.innerHTML = '<option value="">-- Select State --</option>';
    const states = Object.keys(INDIA_LOCATIONS).sort();
    states.forEach(st => {
        const opt = document.createElement('option');
        opt.value = st;
        opt.textContent = st;
        stateEl.appendChild(opt);
    });

    // 2. On State Change: update district dropdown
    stateEl.addEventListener('change', function() {
        const selectedState = this.value;
        districtEl.innerHTML = '<option value="">-- Select District --</option>';

        if (selectedState && INDIA_LOCATIONS[selectedState]) {
            districtEl.removeAttribute('disabled');
            const districts = INDIA_LOCATIONS[selectedState];
            districts.forEach(dist => {
                const opt = document.createElement('option');
                opt.value = dist.name;
                opt.textContent = dist.name;
                opt.dataset.pincode = dist.pincode;
                districtEl.appendChild(opt);
            });
        } else {
            districtEl.setAttribute('disabled', 'true');
        }

        // Trigger change on district to clear or sync
        districtEl.dispatchEvent(new Event('change'));
    });

    // 3. On District Change: auto-populate city & pincode
    districtEl.addEventListener('change', function() {
        const selectedOption = this.options[this.selectedIndex];
        if (selectedOption && selectedOption.value) {
            const districtName = selectedOption.value;
            const defaultPin = selectedOption.dataset.pincode;

            // Auto-fill city with clean district/city name if empty or default
            if (cityEl) {
                // Strip parenthetical text like (Silchar) or clean up for city
                let cleanCity = districtName.replace(/\(.*?\)/g, '').trim();
                // If contains slash like Itanagar / Papum Pare
                if (cleanCity.includes('/')) {
                    cleanCity = cleanCity.split('/')[0].trim();
                }
                cityEl.value = cleanCity;
                cityEl.classList.remove('is-invalid');
            }

            // Auto-fetch & set pincode
            if (pincodeEl && defaultPin) {
                pincodeEl.value = defaultPin;
                pincodeEl.classList.remove('is-invalid');
            }
        }
    });
}
